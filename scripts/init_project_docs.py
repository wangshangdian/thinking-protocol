def main():
    argv = sys.argv[1:]
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0

    target = Path(argv[0]).expanduser().resolve()
    force = "--force" in argv
    dry = "--dry-run" in argv

    if target.exists() and not target.is_dir():
        print("错误：目标路径不是目录 -> %s" % target)
        return 1

    created, skipped = [], []
    for rel, content in T.items():
        path = target / rel
        if path.exists() and not force:
            skipped.append(rel)
            continue
        if dry:
            created.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(rel)

    head = "[dry-run] 将会创建" if dry else "已创建"
    print("目标目录: %s" % target)
    for r in created:
        print("  %s : %s" % (head, r))
    for r in skipped:
        print("  [跳过·已存在] : %s" % r)
    print("")
    print("完成：%d 个，跳过 %d 个。" % (len(created), len(skipped)))
    if skipped and not force:
        print("如需覆盖已存在的文件，加 --force。")
    if not dry:
        print("")
        print("下一步：")
        print("  1. 填 docs/00-项目章程.md（目标 / 边界 / 底层思维）——它是单一事实源")
        print("  2. 之后随时把新想法丢进 docs/03-思路收件箱.md，不必组织语言")
    return 0


if __name__ == "__main__":
    sys.exit(main())
